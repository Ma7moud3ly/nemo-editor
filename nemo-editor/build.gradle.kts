/**
 * Generates `NemoEditorInfo.kt` into `commonMain`, so every target knows the
 * editor's version. Reruns when the version changes.
 */
abstract class GenerateEditorInfo : DefaultTask() {

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val versionName: Property<String>

    @get:Input
    abstract val versionCode: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val file = outputDir.get().asFile.resolve(pkg.replace('.', '/')).resolve("NemoEditorInfo.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package $pkg
            |
            |/** The Nemo Code Editor's version. Generated by `generateEditorInfo`. */
            |public object NemoEditorInfo {
            |    /** This library's version, e.g. `2.0.1`. */
            |    public const val VERSION: String = "${versionName.get()}"
            |
            |    /** This library's version code, increasing with each release. */
            |    public const val VERSION_CODE: Int = ${versionCode.get()}
            |}
            |""".trimMargin(),
        )
    }
}
